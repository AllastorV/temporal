#include "modules/modules.h"
#include <cstdio>

using namespace tp;

static const char* unitName(Unit u) {
    switch (u) {
    case Unit::None: return "";
    case Unit::Frames: return "frames";
    case Unit::Pixels: return "px (full res)";
    case Unit::Degrees: return "deg";
    case Unit::Percent: return "%";
    case Unit::BPM: return "BPM";
    case Unit::FPS: return "fps";
    case Unit::Normalized: return "0..1";
    case Unit::Seconds: return "s";
    }
    return "";
}

static const char* typeName(PType t) {
    switch (t) {
    case PType::Double: return "float";
    case PType::Int: return "int";
    case PType::Choice: return "choice";
    case PType::Bool: return "bool";
    case PType::Color: return "RGB";
    case PType::Point: return "point";
    }
    return "";
}

int main() {
    std::printf("# TEMPORAL modules\n\nGenerated by `tp_docgen` from the module definitions. Do not edit by hand.\n\n");
    std::printf("Every numeric parameter animates (keyframes); choices and booleans do not. Pixel parameters are given in full-resolution pixels and scaled by the host render scale. Points are normalized frame coordinates (0,0 = bottom-left).\n\n");
    for (const ModuleDef* m : allModules()) {
        std::printf("## %s (`com.temporal.%s`)\n\nFamily: %s.%s%s\n\n%s\n\n", m->name.c_str(), m->id.c_str(), m->family.c_str(),
                    m->temporal ? " Temporal (reads neighbouring frames)." : "", m->usesEncoding ? " Processes in linear light (Input Encoding)." : "",
                    m->description.c_str());
        std::printf("| Parameter | id | Type | Default | Range | Unit | Description |\n|---|---|---|---|---|---|---|\n");
        for (const auto& s : m->params) {
            char def[96], range[96];
            if (s.type == PType::Choice) {
                std::snprintf(def, sizeof def, "%s", s.options[static_cast<size_t>(s.def)].c_str());
                std::string opts;
                for (size_t i = 0; i < s.options.size(); ++i) opts += (i ? " / " : "") + s.options[i];
                std::snprintf(range, sizeof range, "%s", opts.substr(0, 95).c_str());
            } else if (s.type == PType::Bool) {
                std::snprintf(def, sizeof def, "%s", s.def != 0 ? "on" : "off");
                range[0] = 0;
            } else if (s.type == PType::Color || s.type == PType::Point) {
                std::snprintf(def, sizeof def, "%.3g, %.3g%s", s.defv[0], s.defv[1], s.type == PType::Color ? (", " + std::to_string(s.defv[2]).substr(0, 5)).c_str() : "");
                range[0] = 0;
            } else {
                std::snprintf(def, sizeof def, "%g", s.def);
                std::snprintf(range, sizeof range, "%g … %g", s.min, s.max);
            }
            std::printf("| %s | `%s` | %s | %s | %s | %s | %s |\n", s.label.c_str(), s.id.c_str(), typeName(s.type), def, range, unitName(s.unit), s.hint.c_str());
        }
        std::printf("\n");
    }
    return 0;
}
